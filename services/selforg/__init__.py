"""Self-organizing knowledge store service (CLAUDE.md §8, §9).

Coordinates background self-organization passes including near-duplicate category merging,
overly broad category splitting, structure anomaly discovery, and append-only audit journaling.
Enforces non-blocking execution and reads all thresholds dynamically from the settings layer.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any

from core.logging import get_logger
